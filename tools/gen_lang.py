#!/usr/bin/env python3
"""tools/strings.py -> firmware/src/lang.h (all strings in flash, one table per language).

    python3 tools/gen_lang.py                  # his cube: ru, uk, en, es
    python3 tools/gen_lang.py --langs uk,en,es --public   # GitHub build: no personal keys

Also checks that every string fits the width it is drawn in (measured with the baked fonts).
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from strings import LANGS, REGIONS, S  # noqa: E402

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT = os.path.join(ROOT, "firmware", "src", "lang.h")
FD = os.path.expanduser("~/Library/Fonts/")

# key (or prefix ending in "_") -> (font file, px, max width) for the fit check. The Russian
# strings are the ones he has looked at on the cube, so a row may always be as wide as its ru.
FIT = [
    ("EMO_ATTN", "Montserrat-Black.ttf", 30, 224),
    ("EMO_", "Montserrat-Black.ttf", 24, 212),
    ("AL_WORD", "Montserrat-Black.ttf", 41, 216),
    ("CLR_WORD", "Montserrat-Black.ttf", 52, 216),
    ("OUT_SAVE", "Montserrat-Black.ttf", 24, 212),
    ("LF_WAIT", "Montserrat-Black.ttf", 24, 216), ("LF_YOUR", "Montserrat-Black.ttf", 24, 212),
    ("WX_", "Montserrat-SemiBold.ttf", 17, 212),
    ("AL_YELLOW", "Montserrat-SemiBold.ttf", 17, 212), ("AL_RED", "Montserrat-SemiBold.ttf", 17, 212),
    ("SETUP", "Montserrat-SemiBold.ttf", 17, 150), ("LF_TITLE", "Montserrat-SemiBold.ttf", 17, 212),
    ("AL_MISSILES", "Montserrat-SemiBold.ttf", 13, 212), ("AL_NEAR", "Montserrat-Bold.ttf", 18, 212),
    ("CLR_OUT", "Montserrat-Bold.ttf", 18, 190), ("LF_COLORS", "Montserrat-SemiBold.ttf", 13, 212),
    ("SUB_", "Montserrat-SemiBold.ttf", 13, 212), ("LF_", "Montserrat-SemiBold.ttf", 13, 212),
    ("PET_", "Montserrat-SemiBold.ttf", 13, 212),
    ("RG", "Montserrat-SemiBold.ttf", 17, 180),
]


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def fit_check(rows, langs):
    try:
        from PIL import ImageFont
    except ImportError:
        return
    bad = 0
    for key, *vals in rows:
        for pre, file, px, maxw in FIT:
            if key.startswith(pre) if pre.endswith("_") or pre == "RG" else key == pre:
                f = ImageFont.truetype(FD + file, px)
                maxw = max(maxw, f.getlength(vals[0]))
                for lang, v in zip(LANGS, vals):
                    if lang in langs and f.getlength(v) > maxw:
                        print(f"  too wide: {key} [{lang}] {v!r} {f.getlength(v):.0f} > {maxw}px")
                        bad += 1
                break
    if bad:
        print(f"{bad} strings too wide")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--langs", default=",".join(LANGS))
    ap.add_argument("--public", action="store_true")
    a = ap.parse_args()
    langs = a.langs.split(",")
    rows = [r for r in S if not (a.public and r[0].startswith("p_"))]
    rows += [(f"RG{i}",) + tuple(r[1:1 + len(LANGS)]) for i, r in enumerate(REGIONS)]  # alert region labels
    out = ["#pragma once", "// Generated by tools/gen_lang.py from tools/strings.py — do not edit by hand.",
           "#include <Arduino.h>", "",
           f"#define LANG_N {len(langs)}",
           f'static const char LANG_CODES[] = "{",".join(langs)}";  // cfg.lang is an index into this', "",
           "enum Str : uint16_t {"]
    out += [f"  T_{k.upper()}," for k, *_ in rows]
    out += ["  T_N", "};", ""]
    for li, lang in enumerate(langs):
        col = LANGS.index(lang)
        for i, (k, *vals) in enumerate(rows):
            out.append(f"static const char L{li}_{i}[] PROGMEM = {cstr(vals[col])};")
    out.append("")
    out.append("static const char *const LANG_TAB[LANG_N][T_N] PROGMEM = {")
    for li in range(len(langs)):
        out.append("  {" + ", ".join(f"L{li}_{i}" for i in range(len(rows))) + "},")
    out.append("};")
    out.append("")
    out.append("// alert regions: key in the ubilling.net.ua feed and a point for the weather (tools/strings.py REGIONS)")
    out.append(f"#define REGION_N {len(REGIONS)}")
    for i, r in enumerate(REGIONS):
        out.append(f"static const char RK{i}[] PROGMEM = {cstr(r[0])};")
    out.append("static const char *const REGION_KEYS[REGION_N] PROGMEM = {" + ", ".join(f"RK{i}" for i in range(len(REGIONS))) + "};")
    out.append("static const float REGION_LAT[REGION_N] = {" + ", ".join(str(r[-2]) for r in REGIONS) + "};")
    out.append("static const float REGION_LON[REGION_N] = {" + ", ".join(str(r[-1]) for r in REGIONS) + "};")
    with open(OUT, "w") as f:
        f.write("\n".join(out) + "\n")
    print(f"wrote {os.path.normpath(OUT)}: {len(rows)} strings x {len(langs)} languages")
    fit_check(rows, langs)


if __name__ == "__main__":
    main()
