#!/usr/bin/env python3
"""Bake anti-aliased Montserrat fonts into firmware/src/aafonts.h.

Each glyph is stored as 4-bit alpha (two pixels per byte, row-major, a
continuous nibble stream) in flash. The firmware blends it against a known
background, or maps it onto a palette ramp inside 4-bit sprites.
"""
import os
import sys
from PIL import Image, ImageDraw, ImageFont

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from strings import S  # noqa: E402

FD = os.path.expanduser("~/Library/Fonts/")
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "firmware", "src", "aafonts.h")

CYR_UP = "АБВГДЕЁЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯІЇЄҐ"
LAT_UP = "ABCDEFGHIJKLMNOPQRSTUVWXYZÁÉÍÓÚÜÑ"
DIGITS = "0123456789"

CYR_LO = CYR_UP.lower()
LAT_LO = LAT_UP.lower()
PUNCT = " ,.:;!?¡¿/%-+°$₴·_()'\"«»—"


def used(*keys):
    """Every letter the given strings use, in all languages (for the one-word fonts)."""
    return "".join(set("".join(v for k, *vals in S if k in keys for v in vals)))

FONTS = [
    # name,       file,                     px, chars
    ("F_BIG",    "Montserrat-Black.ttf",    68, DIGITS + "-:°"),                       # weather temperature, night clock
    ("F_CLOCK",  "Montserrat-Bold.ttf",     34, DIGITS + ":"),                         # weather clock
    ("F_LABEL",  "Montserrat-SemiBold.ttf", 17, CYR_UP + LAT_UP + DIGITS + " ,.:/%-+°$₴·'!¡"),  # top-left labels, date
    ("F_SMALL",  "Montserrat-SemiBold.ttf", 13, CYR_UP + CYR_LO + LAT_UP + LAT_LO + DIGITS + PUNCT),  # sub-lines
    ("F_NUM",    "Montserrat-Bold.ttf",     18, CYR_UP + CYR_LO + LAT_UP + LAT_LO + DIGITS + PUNCT),  # strips
    ("F_PRICE",  "Montserrat-Bold.ttf",     28, LAT_UP + LAT_LO + DIGITS + " .,$₴"),   # prices, Wi-Fi values
    ("F_NOTE",   "Montserrat-Bold.ttf",     24, CYR_UP + CYR_LO + LAT_UP + LAT_LO + DIGITS + PUNCT),  # notes
    ("F_WORD",   "Montserrat-Black.ttf",    24, CYR_UP + LAT_UP + " '!¡?¿"),                         # face state word
    ("F_ATTN",   "Montserrat-Black.ttf",    30, used("EMO_ATTN")),                           # face: needs you
    ("F_ALERT",  "Montserrat-Black.ttf",    41, used("AL_WORD")),
    ("F_CLEAR",  "Montserrat-Black.ttf",    52, used("CLR_WORD")),
    ("F_TIMER",  "Montserrat-Bold.ttf",     36, DIGITS + ": " + used("U_H", "U_MIN")),                    # alert timer, duration
    ("F_PCT",    "Montserrat-Black.ttf",    48, DIGITS),                               # render percent
]


def bake(name, file, px, chars):
    font = ImageFont.truetype(FD + file, px)
    glyphs, data = [], bytearray()
    nib = []
    asc, _ = font.getmetrics()
    for ch in sorted(set(chars), key=ord):
        x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        adv = int(round(font.getlength(ch)))
        start = len(nib)
        if w and h:
            im = Image.new("L", (w, h), 0)
            ImageDraw.Draw(im).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
            for v in im.getdata():
                nib.append((v * 15 + 127) // 255)
        glyphs.append((ord(ch), w, h, x0, y0, adv, start))
    if len(nib) % 2:
        nib.append(0)
    for i in range(0, len(nib), 2):
        data.append((nib[i] << 4) | nib[i + 1])
    lines = [f"// {file} {px}px, {len(glyphs)} glyphs, {len(data)} bytes"]
    lines.append(f"static const AAGlyph {name}_g[] PROGMEM = {{")
    for cp, w, h, x0, y0, adv, off in glyphs:
        lines.append(f"  {{0x{cp:04X}, {w}, {h}, {x0}, {y0}, {adv}, {off}}},")
    lines.append("};")
    lines.append(f"static const uint8_t {name}_b[] PROGMEM = {{")
    for i in range(0, len(data), 24):
        lines.append("  " + ",".join(str(b) for b in data[i:i + 24]) + ",")
    lines.append("};")
    lines.append(f"static const AAFont {name} = {{{name}_g, {len(glyphs)}, {name}_b, {asc}}};")
    return "\n".join(lines), len(data)


def main():
    parts = ["#pragma once", "// Generated by tools/make_fonts.py — do not edit by hand.", "#include <Arduino.h>",
             "struct AAGlyph { uint16_t cp; uint8_t w, h; int8_t xo, yo; uint8_t adv; uint32_t off; };",
             "struct AAFont { const AAGlyph *g; uint16_t n; const uint8_t *bmp; uint8_t ascent; };", ""]
    total = 0
    for f in FONTS:
        src, n = bake(*f)
        parts.append(src)
        parts.append("")
        total += n
    with open(OUT, "w") as fh:
        fh.write("\n".join(parts))
    print(f"wrote {os.path.normpath(OUT)}: {total} bytes of glyph data")


if __name__ == "__main__":
    main()
