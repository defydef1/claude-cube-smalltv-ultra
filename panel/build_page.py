#!/usr/bin/env python3
"""cube_page.html → panel/build/webpage.h (drop-in for firmware/src/webpage.h)

Light minify (comments, indentation). If the result fits in RAW_LIMIT it is
written as the plain INDEX_HTML raw string (served with send_P, no firmware
change); otherwise as a gzipped byte array INDEX_HTML_GZ / INDEX_HTML_GZ_LEN.

    python3 panel/build_page.py [--gz] [--out PATH] [--langs uk,en,es]

The panel's words come from tools/strings.py (PANEL); --langs picks which languages go in
(default: all), and the first one is what the page shows before the cube says otherwise.
"""
import gzip
import json
import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tools"))
from strings import LANG_NAMES, LANGS, PANEL, REGIONS  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "cube_page.html")
OUT = os.path.join(HERE, "build", "webpage.h")
RAW_LIMIT = 30 * 1024


def minify(s):
    # Only whole-line comments: "image/*" in accept= must survive.
    s = re.sub(r"^\s*/\*.*?\*/", "", s, flags=re.S | re.M)
    lines = (l.strip() for l in s.splitlines())
    return "\n".join(l for l in lines if l)


def main():
    out_path = sys.argv[sys.argv.index("--out") + 1] if "--out" in sys.argv else OUT
    langs = sys.argv[sys.argv.index("--langs") + 1].split(",") if "--langs" in sys.argv else LANGS
    i18n = {l: dict({"_name": LANG_NAMES[l], "_regions": [r[1 + LANGS.index(l)] for r in REGIONS]},
                    **{k: v[LANGS.index(l)] for k, v in PANEL.items()}) for l in langs}
    src = open(SRC, encoding="utf-8").read()
    assert "/*I18N*/" in src
    src = src.replace("/*I18N*/", "const LANGS=%s,I18N=%s;" % (json.dumps(langs), json.dumps(i18n, ensure_ascii=False)))
    html = minify(src)
    raw = html.encode("utf-8")
    gz = gzip.compress(raw, 9, mtime=0)
    want_gz = "--gz" in sys.argv or len(raw) > RAW_LIMIT
    head = "#pragma once\n// Generated by panel/build_page.py from panel/cube_page.html — edit that, not this.\n"
    if want_gz:
        body = ",".join("0x%02x" % b for b in gz)
        body = "\n".join(body[i:i + 120] for i in range(0, len(body), 120))
        out = head + ("// Serve with Content-Encoding: gzip.\n#define INDEX_HTML_GZ_LEN %d\n"
                      "const uint8_t INDEX_HTML_GZ[] PROGMEM = {\n%s};\n" % (len(gz), body))
    else:
        assert ')HTML"' not in html
        out = head + 'const char INDEX_HTML[] PROGMEM = R"HTML(' + html + ')HTML";\n'
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    open(out_path, "w", encoding="utf-8").write(out)
    print("minified %d B, gzip %d B → %s (%s)" % (len(raw), len(gz), os.path.normpath(out_path),
                                               "INDEX_HTML_GZ" if want_gz else "INDEX_HTML raw"))


if __name__ == "__main__":
    main()
